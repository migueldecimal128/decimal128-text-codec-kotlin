    private fun hi(h: String) = h.substring(0, 16).toULong(16).toLong()
    private fun lo(h: String) = h.substring(16, 32).toULong(16).toLong()
    private fun hex(a: Long, b: Long) =
        a.toULong().toString(16).padStart(16, '0').uppercase() +
        b.toULong().toString(16).padStart(16, '0').uppercase()

    @Test
    fun decode() {
        for (v in decodeVectors)
            assertEquals(v.text, Decimal128TextCodec.dpd128ToString(hi(v.hex), lo(v.hex)), v.id)
    }

    @Test
    fun encode() {
        for (v in encodeVectors) {
            val out = LongArray(2)
            assertNull(Decimal128TextCodec.dpd128Parse(out, v.text), "${v.id}: ${v.text}")
            assertEquals(v.hex, hex(out[0], out[1]), "${v.id}: ${v.text}")
        }
    }

    /** Rendering then re-parsing normalises a non-canonical encoding. */
    @Test
    fun canonical() {
        for (v in canonicalVectors) {
            val text = Decimal128TextCodec.dpd128ToString(hi(v.input), lo(v.input))
            val out = LongArray(2)
            assertNull(Decimal128TextCodec.dpd128Parse(out, text), "${v.id}: $text")
            assertEquals(v.canonical, hex(out[0], out[1]), "${v.id}: #${v.input} -> \"$text\"")
        }
    }
